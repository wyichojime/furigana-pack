// 規則の語（決+直前ひらがな＝けっ、罰+助詞＝ばつ など）が、別の読みの言い回しに当たっていたもの
describe('規則の語の読み誤りの回帰', () => {
  it.each([
    ['下手人は茂七に決ったじゃないか', '｜決《きま》った'],
    ['人を害める', '｜害《あや》める'],
    ['罰が当たる', '｜罰《ばち》が'],
    ['質に入れる', '｜質《しち》に'],
    ['六か月かかった', '｜六《ろっ》か'],
    ['募金箱に入れる', '｜箱《ばこ》'],
    ['方形周溝墓が見つかった', '｜墓《ぼ》'],
    ['ロスト率は高い', '｜率《りつ》'],
  ])('%s', (text, expected) => {
    expect(ruby.toAozora(text)).toContain(expected);
  });

  // 率+直前カタカナ は助詞が続くときだけにした。「率いる」には付けない
  it('ハドラー率いる の 率 に りつ を付けない', () => {
    expect(ruby.toAozora('ハドラー率いる魔王軍')).not.toContain('｜率《りつ》');
  });
});

// 上の直しで足した語・外した語が、ほかの語を壊していないこと
describe('直しの副作用がないこと', () => {
  it.each([
    ['体罰が当たり前の時代', '｜体罰《たいばつ》'],
    ['硬貨の投入口', '｜投入《とうにゅう》'],
    ['商人達には売らない', '｜商人達《しょうにんたち》'],
    ['探索者達は扉を開けた', '｜探索者《たんさくしゃ》'],
    ['30歳の男', '｜歳《さい》'],
    ['なし崩し的に決まった', '｜的《てき》'],
    ['同月以降は休む', '｜同月《どうげつ》'],
    ['今年以降も続ける', '｜今年《ことし》'],
    ['数か月以前に結婚した', '｜月《げつ》'],
    ['徳だけが人間を幸福にする', '｜人間《にんげん》'],
    ['常磐線に乗る', '｜常磐線《じょうばんせん》'],
  ])('%s', (text, expected) => {
    expect(ruby.toAozora(text)).toContain(expected);
  });

  // 長い語の途中に短い語が当たる誤読（2026-11-06 の点検）。長い語を足し、同じ長さの条件付きの語に負けないよう先頭に置いた
  it.each([
    ['その娘は、半年前のある晩', '｜半年前《はんとしまえ》'],
    ['手鎖五十日、地主', '｜五十日《ごじゅうにち》'],
    ['伊勢屋総兵衛から', '｜総兵衛《そうべえ》'],
    ['塵紙か浅草紙があったら', '｜浅草紙《あさくさがみ》'],
    ['催眠術をかけた', '｜催眠術《さいみんじゅつ》'],
    ['術をかける', '｜術《じゅつ》をかける'],
    ['商売上手な子供', '｜商売上手《しょうばいじょうず》'],
    ['元日の朝', '｜元日《がんじつ》'],
  ])('%s', (text, expected) => {
    expect(ruby.toAozora(text)).toContain(expected);
  });

  // 足した 2 字の語が、既存の語と同じ長さで競ったときに割り込まない（足した語は末尾に置く）
  it.each([
    ['善人的な男', '｜善人《ぜんにん》'],
    ['場合同様に', '｜場合《ばあい》｜同様《どうよう》'],
    ['喪失速度', '｜喪失《そうしつ》｜速度《そくど》'],
    ['質量的な面', '｜質量《しつりょう》'],
  ])('%s', (text, expected) => {
    expect(ruby.toAozora(text)).toContain(expected);
  });

  // 規則の語（直前が登録語の漢字で、直後が漢字でない 1 字）と、よく出る複合語（2026-11-06）
  it.each([
    ['新幹線で行く', '｜新幹線《しんかんせん》'],
    ['研究員が来た', '｜研究員《けんきゅういん》'],
    ['再描画する', '｜再描画《さいびょうが》'],
    ['未分類の項目', '｜未分類《みぶんるい》'],
    ['選択中の行', '｜選択中《せんたくちゅう》'],
  ])('%s', (text, expected) => {
    expect(ruby.toAozora(text)).toContain(expected);
  });

  // 足した複合語が、隣の既存の語をまたいで奪わない
  it.each([
    ['陸軍施設', '｜陸軍《りくぐん》'],
    ['時間制約', '｜制約《せいやく》'],
    ['共有物件', '｜物件《ぶっけん》'],
    ['最高打率', '｜最高《さいこう》'],
    ['大会中止', '｜中止《ちゅうし》'],
    ['同一世代', '｜同一《どういつ》'],
  ])('%s', (text, expected) => {
    expect(ruby.toAozora(text)).toContain(expected);
  });

  // 読みが割れる・長い語の途中に当たりやすいため外した語には付けない
  it.each([
    ['なす術はない', '｜術《じゅつ》'],
    ['元日本代表の選手', '｜元日《がんじつ》'],
    ['フランス法の仏法派', '｜仏法《ぶっぽう》'],
    ['砧右之助', '｜右之《みぎの》'],
  ])('%s', (text, wrong) => {
    expect(ruby.toAozora(text)).not.toContain(wrong);
  });

  // 「吹替え版」（ばん）と「この版」（はん）で読みが割れるため、単独の 版 は「の版」の形だけにした
  it('この版 には はん が付く', () => {
    expect(ruby.toAozora('この版以降')).toContain('｜版《はん》');
  });
  it('吹替え版 には はん を付けない', () => {
    expect(ruby.toAozora('吹替え版のみ')).not.toContain('｜版《はん》');
  });
});
